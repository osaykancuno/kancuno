// viewer.js → viewer.min.js (terser, bundled with Next) → src/KLabViewer.sol (the page as hex constants)
const fs = require('fs'), path = require('path')
const { minify } = require('../../node_modules/next/dist/compiled/terser')
;(async () => {
  const src = fs.readFileSync(path.join(__dirname, 'viewer.js'), 'utf8')
  const js = (await minify(src, { ecma: 2019, compress: { passes: 2 }, mangle: { reserved: ['D'] }, format: { comments: false } })).code
  fs.writeFileSync(path.join(__dirname, 'viewer.min.js'), js)
  const head = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>K1N0 · THE K.LAB</title><style>html,body{margin:0;height:100%;overflow:hidden}canvas{width:100%;height:100%;display:block;touch-action:none;cursor:grab}canvas:active{cursor:grabbing}</style></head><body><canvas id="c" aria-label="The K1N0 in 3D: drag to turn it"></canvas><script>const D="'
  const tail = '";' + js + '</script></body></html>'
  const hex = s => Buffer.from(s, 'utf8').toString('hex')
  const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// @title THE K.LAB viewer
/// @notice The interactive 3D K1N0, fully on-chain: an HTML page with a small WebGL engine
/// (contracts/viewer/viewer.js, generated by viewer/build.cjs) and the token's design bytes.
/// Marketplaces show it from the metadata's animation_url: drag to turn the K, wheel or pinch
/// to zoom, double-click to go back to the view chosen at mint.
contract KLabViewer {
    bytes private constant HEAD = hex"${hex(head)}";
    bytes private constant TAIL = hex"${hex(tail)}";
    bytes16 private constant HEXD = "0123456789abcdef";

    function html(bytes calldata d) external pure returns (bytes memory) {
        bytes memory h = new bytes(d.length * 2);
        for (uint256 i = 0; i < d.length; i++) {
            h[i * 2] = HEXD[uint8(d[i]) >> 4];
            h[i * 2 + 1] = HEXD[uint8(d[i]) & 15];
        }
        return abi.encodePacked(HEAD, h, TAIL);
    }
}
`
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'KLabViewer.sol'), sol)
  // the same page for the site (mint preview, token page, look studio): identical to the NFT
  const ts = `// Generated by contracts/viewer/build.cjs from contracts/viewer/viewer.js: the K1N0 3D piece,
// byte for byte the page the KLabViewer contract puts in every token's animation_url.
export const VIEWER_HEAD = ${JSON.stringify(head)}
export const VIEWER_TAIL = ${JSON.stringify(tail)}
export const viewerHtml = (dataHex: string) => VIEWER_HEAD + dataHex.replace(/^0x/, '').toLowerCase() + VIEWER_TAIL
`
  fs.writeFileSync(path.join(__dirname, '..', '..', 'src', 'lib', 'lab', 'k1n0-viewer.ts'), ts)
  console.log('src/KLabViewer.sol written,', js.length, 'bytes of JS')
})()
