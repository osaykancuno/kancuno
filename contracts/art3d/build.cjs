// art3d/faces.json → src/KLabFaces.sol: the projected faces of the 3D K as one constant
// (per face: group, shade 0-255, length of its SVG path, the path). Run after geometry.cjs.
const fs = require('fs')
const path = require('path')
const faces = JSON.parse(fs.readFileSync(path.join(__dirname, 'faces.json'), 'utf8'))
let hex = ''
for (const f of faces) {
  const d = Buffer.from(f.d, 'ascii')
  if (d.length > 255) throw new Error('path too long')
  hex += [f.group, f.shade, d.length].map(v => v.toString(16).padStart(2, '0')).join('') + d.toString('hex')
}
const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// @title THE K.LAB · the faces of the 3D K
/// @notice Generated by contracts/art3d/build.cjs from art3d/geometry.cjs: the clay K of kancuno.com
/// seen from the site's camera, projected once. Per face: group (0 shadow, 1 X, 3 the four black
/// blocks of the head, 4 centre, 5 front left, 6 front right), shade (0-255), path length, SVG path.
library KLabFaces {
    bytes internal constant FACES = hex"${hex}";
}
`
fs.writeFileSync(path.join(__dirname, '..', 'src', 'KLabFaces.sol'), sol)
console.log('src/KLabFaces.sol:', faces.length, 'faces,', hex.length / 2, 'bytes')
